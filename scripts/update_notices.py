"""Generate deterministic notices with the pinned cargo-about license scanner."""

from __future__ import annotations

import argparse
import json
import subprocess
from pathlib import Path
from typing import Any, cast

ROOT = Path(__file__).resolve().parents[1]


def generate_notices(cargo_about: str) -> tuple[str, str]:
    """Collect the locked extension graph and return notices and SPDX expression."""
    version = subprocess.check_output([cargo_about, "--version"], text=True).strip()
    if version != "cargo-about 0.9.2":
        raise ValueError(f"expected cargo-about 0.9.2, found {version}")
    result = subprocess.check_output(
        [
            cargo_about,
            "generate",
            "--manifest-path",
            "crates/python/Cargo.toml",
            "--config",
            "about.toml",
            "--features",
            "extension-module",
            "--locked",
            "--fail",
            "--format",
            "json",
        ],
        cwd=ROOT,
        text=True,
    )
    data = cast(dict[str, Any], json.loads(result))
    sections = [
        "Third-party notices for topology-checker Python distributions.\n"
        "Generated by cargo-about 0.9.2 from Cargo.lock and about.toml.\n"
        "Targets: Linux x86_64, Windows x86_64, macOS x86_64 and macOS aarch64.\n"
        "Build-only and development-only dependencies are excluded.\n"
        "The project's own MIT license is provided in LICENSE.\n"
    ]
    identifiers = {"MIT"}
    for license_info in sorted(
        data["licenses"], key=lambda item: (item["id"], item["text"])
    ):
        crates = sorted(
            f"{item['crate']['name']} {item['crate']['version']}"
            for item in license_info["used_by"]
            if not item["crate"]["name"].startswith("topology-checker")
        )
        if not crates:
            continue
        # cargo-about groups exception-bearing texts under the base license ID.
        # Retain the SPDX exception when deriving the distribution expression.
        exceptions = {
            item["crate"]["license"]
            for item in license_info["used_by"]
            if " WITH " in item["crate"]["license"]
        }
        identifiers.update(exceptions or {license_info["id"]})
        license_text = license_info["text"].replace("\r\n", "\n").strip()
        sections.append(
            f"License: {license_info['id']}\n"
            f"Used by: {', '.join(crates)}\n\n{license_text}\n"
        )
    return "\n".join(sections), " AND ".join(sorted(identifiers))


def main() -> None:
    """Update the notices or fail when the committed notices are stale."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--cargo-about", default="cargo-about")
    args = parser.parse_args()
    content, expression = generate_notices(args.cargo_about)
    destination = ROOT / "THIRD-PARTY-NOTICES.txt"
    metadata = (ROOT / "pyproject.toml").read_text(encoding="utf-8")
    if f'license = "{expression}"' not in metadata:
        raise SystemExit(f"Set project.license to {expression!r} in pyproject.toml")
    if args.check:
        if destination.read_text(encoding="utf-8") != content:
            raise SystemExit("Notices are stale; run scripts/update_notices.py")
    else:
        destination.write_text(content, encoding="utf-8")
    print(f"License notices are current: {expression}")


if __name__ == "__main__":
    main()
