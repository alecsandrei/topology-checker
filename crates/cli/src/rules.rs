use std::io::{self, Write};
use topology_checker_core::{GeometryKind, Rule};

pub(super) fn render(output: &mut impl Write) -> io::Result<()> {
    writeln!(output, "Available topology rules ({})\n", Rule::ALL.len())?;
    for (kind, heading) in GROUPS {
        let rules = || Rule::ALL.iter().copied().filter(|r| r.inputs().0 == kind);
        writeln!(output, "{heading} ({})\n", rules().count())?;
        for rule in rules() {
            writeln!(output, "  {}", rule.name())?;
            explanation(output, rule.summary())?;
            writeln!(output, "    Needs: {}\n", needs(rule))?;
        }
    }
    writeln!(output, "Usage: topology-checker <group> <rule> <input>")?;
    writeln!(output, "For two layers, add: --other <input>")?;
    writeln!(output, "Rule help: topology-checker <group> <rule> --help")
}

const GROUPS: [(GeometryKind, &str); 4] = [
    (GeometryKind::Point, "Points"),
    (GeometryKind::Line, "Lines"),
    (GeometryKind::Polygon, "Polygons"),
    (GeometryKind::Any, "All geometries"),
];

fn needs(rule: Rule) -> String {
    let (first, second) = rule.inputs();
    match second {
        None => format!("one {}", layer(first)),
        Some(GeometryKind::Any) if first == GeometryKind::Any => {
            "two layers of any geometry type".into()
        }
        Some(other) if other == first => format!("two {}s", layer(first)),
        Some(other) => format!("{} + {}", layer(first), layer(other)),
    }
}

fn layer(kind: GeometryKind) -> &'static str {
    match kind {
        GeometryKind::Point => "point layer",
        GeometryKind::Line => "line layer",
        GeometryKind::Polygon => "polygon layer",
        GeometryKind::Collection => "geometry collection layer",
        GeometryKind::Any => "layer of any geometry type",
        _ => "layer",
    }
}

fn explanation(output: &mut impl Write, text: &str) -> io::Result<()> {
    let mut column = 4;
    write!(output, "    ")?;
    for word in text.split_whitespace() {
        if column > 4 {
            if column + 1 + word.len() > 80 {
                write!(output, "\n    ")?;
                column = 4;
            } else {
                write!(output, " ")?;
                column += 1;
            }
        }
        write!(output, "{word}")?;
        column += word.len();
    }
    writeln!(output)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn explanations_wrap_at_80_columns_without_losing_words() {
        for &rule in Rule::ALL {
            let mut output = Vec::new();
            explanation(&mut output, rule.summary()).unwrap();
            let text = String::from_utf8(output).unwrap();
            assert!(text.ends_with('\n'));
            assert!(
                text.lines()
                    .all(|line| line.starts_with("    ") && line.len() <= 80)
            );
            assert_eq!(
                text.split_whitespace().collect::<Vec<_>>(),
                rule.summary().split_whitespace().collect::<Vec<_>>()
            );
        }
    }

    #[test]
    fn wrapping_includes_indentation_and_keeps_exact_width_lines() {
        let word = "x".repeat(74);
        let mut output = Vec::new();
        explanation(&mut output, &format!("{word} y z")).unwrap();
        assert_eq!(
            String::from_utf8(output).unwrap(),
            format!("    {word} y\n    z\n")
        );
    }

    // Writes docs/rules.md like ts-rs writes web/src/generated; CI checks it is committed.
    #[test]
    fn rule_reference_in_docs_is_current() {
        let mut text = String::from(
            "# Rules\n\n<!-- Generated by `cargo test -p topology-checker` from the core rule registry. Do not edit. -->\n\nRun a rule as `topology-checker <group> <rule>`, or use `rule = \"<group>/<rule>\"` in `topology.toml`. `topology-checker <group> <rule> --help` prints the exact semantics.\n",
        );
        for (kind, heading) in GROUPS {
            let rules = Rule::ALL
                .iter()
                .copied()
                .filter(|r| r.inputs().0 == kind)
                .collect::<Vec<_>>();
            text += &format!(
                "\n## {heading} ({})\n\n| Rule | Needs | Description | ArcGIS | QGIS |\n| --- | --- | --- | --- | --- |\n",
                rules.len()
            );
            for rule in rules {
                text += &format!(
                    "| `{}` | {} | {} | {} | {} |\n",
                    rule.name(),
                    needs(rule),
                    rule.summary(),
                    rule.arcgis().unwrap_or(""),
                    rule.qgis().unwrap_or("")
                );
            }
        }
        let docs = std::path::Path::new(concat!(env!("CARGO_MANIFEST_DIR"), "/../../docs"));
        // The published crate has no docs/ to keep current.
        if docs.is_dir() {
            write_if_changed(&docs.join("rules.md"), &text);
        }
    }

    fn write_if_changed(path: &std::path::Path, text: &str) {
        let current = std::fs::read_to_string(path).map(|t| t.replace("\r\n", "\n"));
        if current.ok().as_deref() != Some(text) {
            std::fs::write(path, text).unwrap();
        }
    }

    #[test]
    fn stale_or_missing_reference_files_are_rewritten() {
        let dir = tempfile::tempdir().unwrap();
        let path = dir.path().join("rules.md");
        write_if_changed(&path, "a\n");
        assert_eq!(std::fs::read_to_string(&path).unwrap(), "a\n");
        write_if_changed(&path, "b\n");
        assert_eq!(std::fs::read_to_string(&path).unwrap(), "b\n");
        // Windows checkouts compare equal after normalising line endings.
        std::fs::write(&path, "b\r\n").unwrap();
        write_if_changed(&path, "b\n");
        assert_eq!(std::fs::read_to_string(&path).unwrap(), "b\r\n");
    }

    #[test]
    fn layer_labels_cover_every_geometry_kind() {
        assert_eq!(layer(GeometryKind::Collection), "geometry collection layer");
    }

    #[test]
    fn rule_help_keeps_technical_registry_descriptions() {
        let command = crate::cli::command();
        for &rule in Rule::ALL {
            let (group, name) = rule.name().split_once('/').unwrap();
            let help = command
                .find_subcommand(group)
                .unwrap()
                .find_subcommand(name)
                .unwrap();
            assert_eq!(help.get_about().unwrap().to_string(), rule.description());
        }
    }
}
